package com.py.angel.dto;

public class AngelOneLoginRequest {

    private String clientCode;
    private String password;      // mpin
    private String totp;          // pre-generated by caller
    private String apiKey;
    private String loginUrl;      // or keep this config-driven in the microservice

    /**
     * @return the clientCode
     */
    public String getClientCode() {
        return clientCode;
    }

    /**
     * @param clientCode the clientCode to set
     */
    public void setClientCode(String clientCode) {
        this.clientCode = clientCode;
    }

    /**
     * @return the password
     */
    public String getPassword() {
        return password;
    }

    /**
     * @param password the password to set
     */
    public void setPassword(String password) {
        this.password = password;
    }

    /**
     * @return the totp
     */
    public String getTotp() {
        return totp;
    }

    /**
     * @param totp the totp to set
     */
    public void setTotp(String totp) {
        this.totp = totp;
    }

    /**
     * @return the apiKey
     */
    public String getApiKey() {
        return apiKey;
    }

    /**
     * @param apiKey the apiKey to set
     */
    public void setApiKey(String apiKey) {
        this.apiKey = apiKey;
    }

    /**
     * @return the loginUrl
     */
    public String getLoginUrl() {
        return loginUrl;
    }

    /**
     * @param loginUrl the loginUrl to set
     */
    public void setLoginUrl(String loginUrl) {
        this.loginUrl = loginUrl;
    }
}
